// Isolated command integration tests. No user-data directory is accessed.
import { chromium } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
const browser = await chromium.connectOverCDP("http://127.0.0.1:9224");
let widget = browser.contexts()[0].pages().find(p => p.url().includes("view=widget"));
if (!widget) widget = await browser.contexts()[0].waitForEvent("page", { timeout: 10000 });
await widget.waitForURL(/view=widget/);
assert(widget, "isolated widget is running");
const invoke = (page, command, args={}) => page.evaluate(({command,args}) => window.__TAURI_INTERNALS__.invoke(command,args),{command,args});
const path = await invoke(widget,"data_path");
assert(path.includes("com.researchflow.acceptance.v130"),"Native checks must use the isolated identifier");
assert(!path.includes("com.researchflow.desktop"));
const fixture=JSON.parse(await readFile("artifacts/v1.3.0/fixture.json","utf8"));
const original=await invoke(widget,"load_data");
assert.deepEqual(original.projects.map(p=>p.id),fixture.projects.map(p=>p.id));
await invoke(widget,"manager_show",{page:"overview"});
let manager=browser.contexts()[0].pages().find(p=>!p.url().includes("view=widget"));
if(!manager) manager=await browser.contexts()[0].waitForEvent("page");
await manager.waitForLoadState();
await invoke(manager,"set_overview_timeline_collapsed",{value:true});
assert.equal(await invoke(widget,"overview_timeline_collapsed"),true);
await invoke(widget,"widget_mode",{mini:true});
assert.equal(await invoke(manager,"overview_timeline_collapsed"),true);
await invoke(manager,"set_overview_timeline_collapsed",{value:false});
assert.equal(await invoke(widget,"widget_is_mini"),true,"Timeline preference preserves mini key");
await invoke(widget,"widget_mode",{mini:false});
let changes=0;
const client=await browser.contexts()[0].newCDPSession(widget);
await client.send("Runtime.addBinding",{name:"rfDataChanged"});
client.on("Runtime.bindingCalled",e=>{if(e.name==="rfDataChanged")changes++;});
const listener=await widget.evaluate(async()=>{
  const id=window.__TAURI_INTERNALS__.transformCallback(()=>window.rfDataChanged("changed"));
  return window.__TAURI_INTERNALS__.invoke("plugin:event|listen",{event:"data-changed",target:{kind:"Any"},handler:id});
});
const next=structuredClone(original);next.projects[0].background="仅隔离原生保存重读测试";
const saved=await invoke(manager,"save_data",{data:next,expected:original.revision});
assert.equal(saved.revision,original.revision+1);
assert.equal((await invoke(widget,"load_data")).projects[0].background,next.projects[0].background);
assert.equal(changes,1,"Native data-changed is received in other WebView");
const restored=await invoke(manager,"save_data",{data:original,expected:saved.revision});
assert.equal(restored.projects[0].background,original.projects[0].background);
await invoke(widget,"plugin:event|unlisten",{event:"data-changed",eventId:listener});
await client.detach();
await invoke(manager,"hide_all");
assert.equal((await invoke(widget,"desktop_state")).widget.visible,false);
await invoke(widget,"widget_show");
await invoke(widget,"manager_show",{page:"overview"});
await manager.reload();
await manager.waitForLoadState();
await manager.screenshot({path:"artifacts/v1.3.0/native-webview-overview.png"});
await widget.screenshot({path:"artifacts/v1.3.0/native-webview-widget.png"});
await invoke(widget,"set_top",{value:true});
assert.equal((await invoke(widget,"desktop_state")).widget.alwaysOnTop,true);
await invoke(widget,"set_top",{value:false});
await invoke(widget,"widget_mode",{mini:true});
await widget.screenshot({path:"artifacts/v1.3.0/native-webview-capsule.png"});
await invoke(manager,"set_overview_timeline_collapsed",{value:true});
await writeFile("artifacts/v1.3.0/native-commands.json",JSON.stringify({passed:true,dataPath:path,multiWindowSync:true,preferenceKeysPreserved:true,saveReread:true,hideRestore:true,desktopState:await invoke(widget,"desktop_state")},null,2));
console.log("Isolated native preferences/save/reread/multi-window/hide-restore checks passed.");
// Disconnect the harness without sending Browser.close to the hosted WebView.
process.exit(0);
