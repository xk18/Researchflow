  await page.evaluate(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='researchflow-v1'&&!sessionStorage.getItem('allow-map-save'))throw Error('disk full');original.call(this,k,v);};});
