import { test, expect } from "@playwright/test";
import { demoData } from "../fixtures";

test("项目日期只显示节点，时间轴范围与重点切换持久化", async ({ page }) => {
  await page.clock.setFixedTime(new Date("2026-10-14T12:00:00+08:00"));
  const d = demoData();
  d.settings.theme = "light";
  d.settings.focusProjectId = d.projects[0].id;
  await page.goto("/");
  await page.evaluate((d) => localStorage.setItem("researchflow-v1", JSON.stringify(d)), d);
  await page.goto("/?page=projects");
  await page.getByRole("button", { name: "编辑", exact: true }).first().click();
  await page.getByLabel("项目启动日期（可选）").fill("2026-10-10");
  await page.getByLabel("目标完成日期（可选）").fill("2026-10-30");
  await page.getByRole("button", { name: "保存项目", exact: true }).click();
  await page.getByRole("button", { name: "科研规划", exact: true }).click();
  await expect(page.locator('[data-date="2026-10-11"] .calendar-tag')).toHaveCount(0);
  await expect(page.locator('[data-date="2026-10-10"] .calendar-tag')).toHaveCount(1);
  await page.getByRole("button", { name: "时间轴", exact: true }).click();
  const range = page.locator('.timeline-bar.project-dates').first();
  await expect(range).toBeVisible();
  await range.click();
  await expect(page.getByRole("heading", { name: "编辑科研项目", exact: true })).toBeVisible();
  await page.getByLabel("目标完成日期（可选）").fill("2026-11-05");
  await page.getByRole("button", { name: "保存项目", exact: true }).click();
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem("researchflow-v1")!));
  await expect.poll(async () => (await read()).projects[0].targetDate).toBe("2026-11-05");
  expect((await read()).planPeriods).toHaveLength(0);
  await page.reload();
  await page.getByRole("button", { name: "时间轴", exact: true }).click();
  await expect(page.locator(".timeline-bar.project-dates").first()).toHaveAttribute("title", /2026-11-05/);
  await page.locator(".timeline-bar.project-dates").first().click();
  await page.getByLabel("项目启动日期（可选）").fill("");
  await page.getByRole("button", { name: "保存项目", exact: true }).click();
  await expect(page.locator(".timeline-bar.project-dates")).toHaveCount(0);
  await page.getByRole("button", { name: "科研项目", exact: true }).click();
  await page.locator('.project-more > summary').first().click();
  await page.getByRole("button", { name: "取消重点", exact: true }).first().click();
  await expect.poll(async () => (await read()).projects[0].priority).toBe(false);
  expect((await read()).settings.focusProjectId).toBeUndefined();
  await page.getByRole("button", { name: "设为重点", exact: true }).first().click();
  await page.reload();
  expect((await read()).settings.focusProjectId).toBe(d.projects[0].id);
  expect((await read()).tasks).toHaveLength(d.tasks.length);
  expect((await read()).results).toHaveLength(d.results.length);
});
